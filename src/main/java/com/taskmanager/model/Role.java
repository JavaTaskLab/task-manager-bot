package com.taskmanager.model;

/**
 * Роли пользователей в системе.
 */
public enum Role {
    MANAGER,    // Менеджер — видит все задачи, назначает исполнителей, ставит дедлайны
    EXECUTOR,   // Исполнитель — видит только свои задачи, меняет их статус
    OBSERVER    // Наблюдатель — только просмотр
}